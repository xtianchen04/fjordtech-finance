function ententeEmploi(org, worker, lang = 'fr') {
  const w = worker ?? {}
  const en = lang === 'en'
  const employer = esc(org?.legal_name || org?.name || (en ? 'the employer' : "l'employeur"))
  const name = esc(w.full_name || (en ? 'the worker' : 'le travailleur'))
  const wage = w.offered_wage != null ? esc(w.offered_wage) + (en ? ' $/hour' : ' $/heure') : '____________________'
  const hours = w.offered_hours != null ? esc(w.offered_hours) : '____________________'
  const occ = esc(w.occupation || '____________________')
  const body = en
    ? `
    <p>This employment agreement is entered into between <b>${employer}</b> ("the employer") and
    <b>${name}</b> ("the worker"), in accordance with the requirements of the
    ${esc(w.program || 'IMP/TFWP')} program and the Immigration and Refugee Protection Regulations (IRPR).</p>

    <h2>1. Position and work location</h2>
    <p>Occupation: <b>${occ}</b><br>
    Work province: <b>${provinceName(w.work_province)}</b><br>
    Start date: <b>${fmtDate(w.start_date, lang)}</b></p>

    <h2>2. Pay and schedule</h2>
    <p>Offered wage: <b>${wage}</b><br>Hours per week: <b>${hours}</b></p>
    <p>The wage paid will be substantially the same as in the job offer (R209.2(1)(a)(iii)).</p>

    <h2>3. Working conditions</h2>
    <p>The employer undertakes to comply with federal and provincial labour laws, to provide a
    workplace free of abuse (R196.2), and to give the worker information about their rights in Canada.</p>

    <h2>4. Fees</h2>
    <p>No recruitment fees are charged to the worker (R303.1(1)).</p>

    <div class="sign">
      <div>Employer signature — date</div>
      <div>Worker signature — date</div>
    </div>`
    : `
    <p>La présente entente d'emploi est conclue entre <b>${employer}</b>
    (« l'employeur ») et <b>${name}</b> (« le travailleur »),
    conformément aux exigences du programme ${esc(w.program || 'PMI/PTET')} et au Règlement sur
    l'immigration et la protection des réfugiés (RIPR).</p>

    <h2>1. Poste et lieu de travail</h2>
    <p>Profession : <b>${occ}</b><br>
    Province de travail : <b>${provinceName(w.work_province)}</b><br>
    Date de début : <b>${fmtDate(w.start_date, lang)}</b></p>

    <h2>2. Rémunération et horaire</h2>
    <p>Salaire offert : <b>${wage}</b><br>Heures par semaine : <b>${hours}</b></p>
    <p>Le salaire versé sera substantiellement le même que celui de l'offre d'emploi (R209.2(1)(a)(iii)).</p>

    <h2>3. Conditions de travail</h2>
    <p>L'employeur s'engage à respecter les lois fédérales et provinciales du travail, à offrir un
    milieu exempt d'abus (R196.2) et à fournir au travailleur l'information sur ses droits au Canada.</p>

    <h2>4. Frais</h2>
    <p>Aucuns frais de recrutement ne sont facturés au travailleur (R303.1(1)).</p>

    <div class="sign">
      <div>Signature de l'employeur — date</div>
      <div>Signature du travailleur — date</div>
    </div>`
  return wrap(en ? 'Employment agreement' : "Entente d'emploi", body, org, lang)
}

function registreConformite(org, workers, complianceByWorker, score, lang = 'fr') {
  const en = lang === 'en'
  const rows = workers
    .map((w) => {
      const c = complianceByWorker[w.id] ?? []
      const ok = c.filter((r) => r.status === 'ok').length
      const app = c.filter((r) => r.status !== 'na').length
      return `<tr><td>${esc(w.full_name)}</td><td>${esc(w.occupation || '—')}</td>
        <td>${esc(w.program)}</td><td>${fmtDate(w.permit_expiry, lang)}</td>
        <td>${app ? Math.round((ok / app) * 100) : 0} %</td></tr>`
    })
    .join('')

  const body = en
    ? `
    <p>Summary of the organization's compliance status, ready to present during an IRCC or ESDC inspection.</p>
    <h2>Overall readiness score: <b>${score} %</b></h2>
    <h2>Foreign workers</h2>
    <table>
      <thead><tr><th>Name</th><th>Occupation</th><th>Program</th><th>Permit expiry</th><th>Score</th></tr></thead>
      <tbody>${rows || '<tr><td colspan="5">No worker registered.</td></tr>'}</tbody>
    </table>
    <p>Supporting documents are kept for 6 years in accordance with section R209.4 of the IRPR.</p>`
    : `
    <p>Récapitulatif de l'état de conformité de l'organisation, prêt à être présenté lors d'une
    inspection d'IRCC ou d'ESDC.</p>
    <h2>Score global de préparation : <b>${score} %</b></h2>
    <h2>Travailleurs étrangers</h2>
    <table>
      <thead><tr><th>Nom</th><th>Profession</th><th>Programme</th><th>Expiration permis</th><th>Score</th></tr></thead>
      <tbody>${rows || '<tr><td colspan="5">Aucun travailleur enregistré.</td></tr>'}</tbody>
    </table>
    <p>Les documents justificatifs sont conservés pendant 6 ans conformément à l'article R209.4 du RIPR.</p>`
  return wrap(en ? 'Compliance register' : 'Registre de conformité', body, org, lang)
}

