/**
 * Génère un document par clé et l'ouvre dans un nouvel onglet imprimable.
 * @param {string} key  identifiant du modèle
 * @param {object} ctx  { org, worker, workers, complianceByWorker, score }
 */
export function generateDocument(key, ctx = {}) {
  const { org, worker, workers = [], complianceByWorker = {}, score = 0, lang = 'fr' } = ctx
  let html
  switch (key) {
    case 'entente':
      html = ententeEmploi(org, worker, lang)
      break
    case 'registre':
      html = registreConformite(org, workers, complianceByWorker, score, lang)
      break
    case 'reponse':
      html = reponseInspection(org, lang)
      break
    case 'declaration':
      html = declarationChangement(org, lang)
      break
    default:
      throw new Error('Modèle de document inconnu : ' + key)
  }

  const win = window.open('', '_blank')
  if (!win) {
    // Repli : téléchargement du fichier HTML si les pop-ups sont bloqués.
    const blob = new Blob([html], { type: 'text/html' })
    const url = URL.createObjectURL(blob)
    const a = document.createElement('a')
    a.href = url
    a.download = `${key}.html`
    a.click()
    URL.revokeObjectURL(url)
    return
  }
  win.document.write(html)
  win.document.close()
}

